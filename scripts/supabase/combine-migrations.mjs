// Builds supabase/apply-all-migrations.sql: every migration in order, in one
// file, to paste into the Supabase SQL editor once. Each migration is written
// to be safe to re-run, so running the whole file on a database that already
// has some of them only adds what is missing.
//   npm run db:combine
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "supabase");

export function combinedMigrations() {
  const dir = join(root, "migrations");
  const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
  const parts = [
    `-- StrikeLab: all migrations in order (${files[0]} to ${files[files.length - 1]}).`,
    "-- GENERATED by `npm run db:combine` from supabase/migrations. Do not edit this file.",
    "-- Safe to run on a database that already has some of them (each is re-runnable).",
    "-- After running, run scripts/metrics/check-migrations.sql: every row should say 'applied'.",
    "",
  ];
  for (const f of files) {
    parts.push(`-- ============================================================`, `-- ${f}`, `-- ============================================================`, readFileSync(join(dir, f), "utf8").trimEnd(), "");
  }
  return parts.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, "apply-all-migrations.sql"), combinedMigrations());
  console.log("[db:combine] wrote supabase/apply-all-migrations.sql");
}
